grant select on public.social_links, public.appearance to anon;
grant select, insert, update, delete on public.profiles, public.social_links to authenticated;
grant select, update on public.appearance to authenticated;
grant select, insert on public.analytics_events to authenticated;
grant select on public.subscriptions to authenticated;
grant usage, select on sequence public.analytics_events_id_seq to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('avatars', 'avatars', true, 5242880, array['image/jpeg','image/png','image/webp']),
  ('banners', 'banners', true, 8388608, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

create policy "Public profile images are readable" on storage.objects for select to anon, authenticated
using (bucket_id in ('avatars', 'banners'));
create policy "Users upload profile images" on storage.objects for insert to authenticated
with check (bucket_id in ('avatars', 'banners') and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "Users update profile images" on storage.objects for update to authenticated
using (bucket_id in ('avatars', 'banners') and owner_id = (select auth.uid())::text)
with check (bucket_id in ('avatars', 'banners') and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "Users delete profile images" on storage.objects for delete to authenticated
using (bucket_id in ('avatars', 'banners') and owner_id = (select auth.uid())::text);
