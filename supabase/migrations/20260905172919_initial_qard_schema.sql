create policy "Published profiles are public" on public.profiles for select to anon, authenticated
using (published or (select auth.uid()) = user_id);
create policy "Users insert their profile" on public.profiles for insert to authenticated
with check ((select auth.uid()) = user_id);
create policy "Users update their profile" on public.profiles for update to authenticated
using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users delete their profile" on public.profiles for delete to authenticated
using ((select auth.uid()) = user_id);

create policy "Published links are public" on public.social_links for select to anon, authenticated
using (exists (select 1 from public.profiles p where p.id = profile_id and (p.published or p.user_id = (select auth.uid()))));
create policy "Users insert own links" on public.social_links for insert to authenticated
with check (exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())));
create policy "Users update own links" on public.social_links for update to authenticated
using (exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())))
with check (exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())));
create policy "Users delete own links" on public.social_links for delete to authenticated
using (exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())));

create policy "Published appearance is public" on public.appearance for select to anon, authenticated
using (exists (select 1 from public.profiles p where p.id = profile_id and (p.published or p.user_id = (select auth.uid()))));
create policy "Users update own appearance" on public.appearance for update to authenticated
using (exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())))
with check (exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())));

create policy "Users read own analytics" on public.analytics_events for select to authenticated
using (exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())));
create policy "Users record own QR downloads" on public.analytics_events for insert to authenticated
with check (event_type = 'qr_download' and exists (select 1 from public.profiles p where p.id = profile_id and p.user_id = (select auth.uid())));

create policy "Users read own subscription" on public.subscriptions for select to authenticated
using ((select auth.uid()) = user_id);

grant usage on schema public to anon, authenticated;
