create or replace function private.handle_qard_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  base_slug text;
  generated_slug text;
  qard_profile_id uuid;
begin
  base_slug := coalesce(nullif(trim(both '-' from regexp_replace(lower(split_part(coalesce(new.email, 'qard'), '@', 1)), '[^a-z0-9]+', '-', 'g')), ''), 'qard');
  generated_slug := left(base_slug, 22) || '-' || substr(new.id::text, 1, 6);

  insert into public.qard_profiles (user_id, slug, display_name)
  values (new.id, generated_slug, coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(new.email, 'Ma Qard'), '@', 1)))
  on conflict (user_id) do update set user_id = excluded.user_id
  returning id into qard_profile_id;

  insert into public.qard_appearance (profile_id) values (qard_profile_id)
  on conflict (profile_id) do nothing;
  insert into public.qard_subscriptions (user_id) values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

revoke all on function private.handle_qard_new_user() from public;
drop trigger if exists on_auth_qard_user_created on auth.users;
create trigger on_auth_qard_user_created after insert on auth.users for each row execute function private.handle_qard_new_user();

insert into public.qard_profiles (user_id, slug, display_name)
select
  id,
  left(coalesce(nullif(trim(both '-' from regexp_replace(lower(split_part(coalesce(email, 'qard'), '@', 1)), '[^a-z0-9]+', '-', 'g')), ''), 'qard'), 22) || '-' || substr(id::text, 1, 6),
  coalesce(nullif(raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(email, 'Ma Qard'), '@', 1))
from auth.users
on conflict (user_id) do nothing;

insert into public.qard_appearance (profile_id)
select id from public.qard_profiles on conflict (profile_id) do nothing;
insert into public.qard_subscriptions (user_id)
select id from auth.users on conflict (user_id) do nothing;

